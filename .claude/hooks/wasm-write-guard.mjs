#!/usr/bin/env node
// PreToolUse hook: block Edit/Write against plugins/obsidian-ee/src/wasm/, the
// wasm-pack output (gitignored at plugins/obsidian-ee/.gitignore:10). When that
// artifact is stale, tsc errors point INTO collab_wasm.d.ts (e.g. TS2614 "has no
// exported member"). The tempting wrong fix is hand-adding the missing export to
// the .d.ts: tsc goes green, the change shows in no diff (dir is gitignored),
// and the next ./scripts/build-wasm.sh silently reverts it. This guard makes
// that structurally impossible — always rebuild, or fix crates/collab-wasm/.
// PreToolUse semantics differ from PostToolUse: exit 2 BLOCKS the tool call
// (stderr goes back to the model as the reason); exit 0 allows it.
import { execFileSync } from 'node:child_process';
import path from 'node:path';

let raw = '';
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  try {
    const fp = JSON.parse(raw)?.tool_input?.file_path ?? '';
    if (!fp) return process.exit(0);
    let root;
    try {
      root = execFileSync('git', ['-C', path.dirname(fp), 'rev-parse', '--show-toplevel'], { stdio: 'pipe' })
        .toString()
        .trim();
    } catch {
      root = process.env.CLAUDE_PROJECT_DIR || process.cwd();
    }
    const rel = path.relative(root, fp).split(path.sep).join('/');
    if (!rel.startsWith('plugins/obsidian-ee/src/wasm/')) return process.exit(0);
    process.stderr.write(
      `${rel} is generated by wasm-pack (gitignored — plugins/obsidian-ee/.gitignore:10). ` +
        `Hand-editing it is silently reverted by the next build and invisible in git diff. ` +
        `Run ./scripts/build-wasm.sh to regenerate it, or change the Rust in crates/collab-wasm/ if an export is genuinely missing.\n`,
    );
    process.exit(2);
  } catch {
    process.exit(0);
  }
});
